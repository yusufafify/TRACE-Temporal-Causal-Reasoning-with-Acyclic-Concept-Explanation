"""
Cached LUMIERE Dataset Loader

This dataset loads preprocessed data from .pt cache files.
Much faster than loading and processing NIfTI files on-the-fly.

Usage:
    1. First run: python preprocess_and_cache.py --root /path/to/LUMIERE
    2. Then use this dataset in training
"""

import torch
from torch.utils.data import Dataset
import numpy as np
import json
from pathlib import Path


def collate_fn_skip_strings(batch):
    """
    Custom collate that stacks tensors/arrays normally while leaving
    string fields (patient_id, baseline_case, followup_case) as plain
    Python lists.  This prevents pin_memory from attempting to CUDA-pin
    non-tensor objects, which causes ``cudaErrorInvalidValue``.
    """
    from torch.utils.data.dataloader import default_collate
    tensor_keys = [k for k, v in batch[0].items() if isinstance(v, (torch.Tensor, int, float, np.ndarray))]
    string_keys = [k for k, v in batch[0].items() if isinstance(v, str)]
    out = default_collate([{k: sample[k] for k in tensor_keys} for sample in batch])
    for k in string_keys:
        out[k] = [sample[k] for sample in batch]
    return out


class CachedLUMIEREDataset(Dataset):
    """
    Dataset that loads from preprocessed cache files.
    
    This is much faster than LUMIERETemporalDataset because:
    - No NIfTI loading
    - No normalization/resizing
    - No segmentation processing
    - Direct tensor loading from disk
    """
    
    def __init__(
        self,
        cache_dir,
        patient_ids=None,
        validate_config=True,
        include_time_gap=False,
        include_spd=False
    ):
        """
        Args:
            cache_dir: Directory containing cached .pt files
            patient_ids: List of patient IDs to include (for k-fold splits)
            validate_config: Whether to validate cache against global config
            include_time_gap: If True, return normalized time gap (delta T) in each sample.
                              Requires the cache to have been generated by
                              preprocess_and_cache_time_gap.py.
            include_spd: If True, return SPD (Sum of Products of Diameters) in each sample.
                         Requires the cache to have been generated by
                         preprocess_and_cache_time_gap_SPD.py.
        """
        self.cache_dir = Path(cache_dir)
        self.include_time_gap = include_time_gap
        self.include_spd = include_spd

        # Load pair index
        index_file = self.cache_dir / 'pair_index.json'
        if not index_file.exists():
            raise FileNotFoundError(
                f"Pair index not found: {index_file}\n"
                f"Please run preprocess_and_cache.py first to generate cached data."
            )
        
        with open(index_file, 'r') as f:
            all_pairs = json.load(f)
        
        # Validate cache configuration if requested
        if validate_config:
            self._validate_cache_config()
        
        # Filter by patient_ids if provided
        if patient_ids is not None:
            self.pairs = [
                pair for pair in all_pairs 
                if pair['patient_id'] in patient_ids
            ]
        else:
            self.pairs = all_pairs
        
        print(f"Loaded {len(self.pairs)} temporal pairs from "
              f"{len(set(p['patient_id'] for p in self.pairs))} patients")
    
    def _validate_cache_config(self):
        """
        Validate that cache was created with same config as global_config.yaml.
        Raises error if mismatch detected.
        """
        metadata_file = self.cache_dir / 'cache_metadata.json'
        if not metadata_file.exists():
            print("Warning: Cache metadata not found. Cannot validate preprocessing parameters.")
            print("This cache may have been created with different settings.")
            return
        
        # Load cache metadata
        with open(metadata_file, 'r') as f:
            cache_config = json.load(f)
        
        # Load global config
        import yaml
        global_config_path = Path(__file__).parent.parent.parent / 'global_config.yaml'
        if not global_config_path.exists():
            print("Warning: global_config.yaml not found. Cannot validate cache.")
            return
        
        with open(global_config_path, 'r') as f:
            global_config = yaml.safe_load(f)
        
        # Validate critical parameters
        errors = []
        
        # Check if this is MNI-standardized data (preprocessed by teammate)
        is_mni_cache = cache_config.get('preprocessed_by_teammate', False)
        
        if is_mni_cache:
            print("Detected MNI-standardized cache (preprocessed by teammate)")
            print("Skipping normalization and registration validation checks")
        
        # Skip normalization check for MNI cache (already standardized)
        if not is_mni_cache:
            if cache_config['normalize'] != global_config['preprocessing']['normalization_method']:
                errors.append(
                    f"Normalization mismatch: cache uses '{cache_config['normalize']}' "
                    f"but config specifies '{global_config['preprocessing']['normalization_method']}'"
                )
        
        if cache_config['spatial_size'] != global_config['preprocessing']['spatial_size']:
            errors.append(
                f"Spatial size mismatch: cache uses {cache_config['spatial_size']} "
                f"but config specifies {global_config['preprocessing']['spatial_size']}"
            )
        
        # Skip use_registered check for MNI cache (not applicable)
        if not is_mni_cache and 'use_registered' in cache_config:
            if cache_config['use_registered'] != global_config['datasets']['lumiere']['use_registered']:
                errors.append(
                    f"Registration mismatch: cache uses_registered={cache_config['use_registered']} "
                    f"but config specifies {global_config['datasets']['lumiere']['use_registered']}"
                )
        
        if errors:
            print("\n" + "="*60)
            print("CACHE CONFIGURATION MISMATCH DETECTED")
            print("="*60)
            for error in errors:
                print(f"ERROR: {error}")
            print("\nThe cached data was created with different preprocessing parameters.")
            print("Please regenerate the cache by running:")
            print("  ./preprocess_data.sh")
            print("="*60 + "\n")
            raise ValueError("Cache configuration mismatch. Please regenerate cache.")
        else:
            print(f"✓ Cache validation passed (created: {cache_config.get('created_at', 'unknown')})")
    
    def __len__(self):
        return len(self.pairs)
    
    def __getitem__(self, idx):
        """
        Load a preprocessed temporal pair.
        
        Returns:
            dict with keys:
                - 'baseline': [4, D, H, W] - Baseline volume
                - 'followup': [4, D, H, W] - Follow-up volume
                - 'volumes_t': [2] - Ground truth volumes at baseline
                - 'volumes_t1': [2] - Ground truth volumes at follow-up
                - 'new_lesion_flag': [1] - Binary flag for new lesion
                - 'rano_label': int - RANO classification (0-3)
                - 'patient_id': str
                - 'baseline_case': str
                - 'followup_case': str
        """
        pair = self.pairs[idx]
        
        # Load pair-level cache (our own trusted files)
        # Handle both absolute and relative paths in pair_index.json
        pair_cache_file = Path(pair['cache_file'])
        if not pair_cache_file.is_absolute():
            # If relative, make it relative to cache_dir (not current working dir)
            pair_cache_file = self.cache_dir / pair_cache_file.name
        
        pair_data = torch.load(pair_cache_file, weights_only=False)
        
        # Load baseline and followup from their individual caches
        # Handle both absolute and relative paths
        baseline_cache_path = Path(pair_data['baseline_cache'])
        followup_cache_path = Path(pair_data['followup_cache'])
        
        if not baseline_cache_path.is_absolute():
            baseline_cache_path = self.cache_dir / baseline_cache_path.name
        if not followup_cache_path.is_absolute():
            followup_cache_path = self.cache_dir / followup_cache_path.name
        
        baseline_data = torch.load(baseline_cache_path, weights_only=False)
        followup_data = torch.load(followup_cache_path, weights_only=False)
        
        # Apply log1p transformation to volumes (cache stores raw cm³)
        # log(1+x) stabilizes regression for volumes spanning multiple scales
        # Use torch.log1p to keep everything in tensor space (avoid numpy conversion issues)
        volumes_t_tensor = baseline_data['volumes']
        volumes_t1_tensor = followup_data['volumes']
        
        # Ensure they're tensors and apply log1p
        if not isinstance(volumes_t_tensor, torch.Tensor):
            volumes_t_tensor = torch.tensor(volumes_t_tensor, dtype=torch.float32)
        if not isinstance(volumes_t1_tensor, torch.Tensor):
            volumes_t1_tensor = torch.tensor(volumes_t1_tensor, dtype=torch.float32)
        
        volumes_t_log = torch.log1p(volumes_t_tensor.float())
        volumes_t1_log = torch.log1p(volumes_t1_tensor.float())
        
        sample = {
            'baseline': baseline_data['volume'],  # [4, 128, 128, 128]
            'followup': followup_data['volume'],  # [4, 128, 128, 128]
            'volumes_t': volumes_t_log,  # [2] - already a tensor
            'volumes_t1': volumes_t1_log,  # [2] - already a tensor
            'new_lesion_flag': torch.tensor([pair_data['new_lesion_flag']], dtype=torch.float32),  # [1]
            'rano_label': pair_data['rano_label'],  # int
            'patient_id': pair_data['patient_id'],  # str
            'baseline_case': pair_data['baseline_case'],  # str
            'followup_case': pair_data['followup_case']  # str
        }

        if self.include_time_gap:
            # 'time_gap' must have been stored by preprocess_and_cache_time_gap.py
            time_gap_val = pair_data.get('time_gap', 0.0)  # Default to 0.0 if not present
            sample['time_gap'] = torch.tensor(
                [time_gap_val], dtype=torch.float32
            )  # [1] normalized weeks / 52

        if self.include_spd:
            # 'spd_t' and 'spd_t1' must have been stored by preprocess_and_cache_time_gap_SPD.py
            spd_t_val = pair_data.get('spd_t', 0.0)   # Baseline SPD, default 0.0
            spd_t1_val = pair_data.get('spd_t1', 0.0)  # Follow-up SPD, default 0.0
            sample['spd_t'] = torch.tensor([spd_t_val], dtype=torch.float32)   # [1] cm²
            sample['spd_t1'] = torch.tensor([spd_t1_val], dtype=torch.float32)  # [1] cm²

        return sample


def build_cached_dataloaders(
    cache_dir,
    train_patient_ids,
    val_patient_ids,
    batch_size=4,
    num_workers=8,
    pin_memory=True,
    persistent_workers=True,
    prefetch_factor=2,
    include_time_gap=False,
    include_spd=False
):
    """
    Build training and validation dataloaders from cached data.

    Args:
        cache_dir: Directory containing cached .pt files
        train_patient_ids: List of patient IDs for training
        val_patient_ids: List of patient IDs for validation
        batch_size: Batch size
        num_workers: Number of data loading workers
        pin_memory: Pin memory for faster GPU transfer
        persistent_workers: Keep workers alive between epochs
        prefetch_factor: Number of batches to prefetch per worker
        include_time_gap: If True, each sample will contain a 'time_gap' tensor.
        include_spd: If True, each sample will contain 'spd_t' and 'spd_t1' tensors.

    Returns:
        train_loader, val_loader
    """
    from torch.utils.data import DataLoader
    
    # Create datasets
    train_dataset = CachedLUMIEREDataset(
        cache_dir=cache_dir,
        patient_ids=train_patient_ids,
        include_time_gap=include_time_gap,
        include_spd=include_spd
    )

    val_dataset = CachedLUMIEREDataset(
        cache_dir=cache_dir,
        patient_ids=val_patient_ids,
        include_time_gap=include_time_gap,
        include_spd=include_spd
    )
    
    # Create dataloaders with optimized settings
    train_loader = DataLoader(
        train_dataset,
        batch_size=batch_size,
        shuffle=True,
        num_workers=num_workers,
        pin_memory=pin_memory,
        persistent_workers=persistent_workers if num_workers > 0 else False,
        prefetch_factor=prefetch_factor if num_workers > 0 else None
    )
    
    val_loader = DataLoader(
        val_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=pin_memory,
        persistent_workers=persistent_workers if num_workers > 0 else False,
        prefetch_factor=prefetch_factor if num_workers > 0 else None
    )
    
    return train_loader, val_loader
